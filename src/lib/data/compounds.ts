export function searchCompounds(q: string, category?: string, access?: string) {
  const s = q.trim().toLowerCase();
  return COMPOUNDS.filter((c) => {
    if (category && c.category !== category) return false;
    if (access && c.access !== access) return false;
    if (!s) return true;
    return [c.name, ...(c.aka ?? []), c.what, c.purpose, c.category, ...c.concerns].join(" ").toLowerCase().includes(s);
  });
}
