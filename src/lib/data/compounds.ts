export function references(c: Compound): { label: string; url: string }[] {
  const q = encodeURIComponent(c.term ?? c.name.replace(/\(.*?\)/g, "").trim());
  const refs = [
    { label: "MedlinePlus (NIH) — consumer drug & health info", url: `https://vsearch.nlm.nih.gov/vivisimo/cgi-bin/query-meta?v%3Aproject=medlineplus&v%3Asources=medlineplus-bundle&query=${q}` },
    { label: "StatPearls / NCBI Bookshelf — clinical review", url: `https://www.ncbi.nlm.nih.gov/books/?term=${q}` },
    { label: "PubMed — peer-reviewed literature (reviews first)", url: `https://pubmed.ncbi.nlm.nih.gov/?term=${q}&filter=pubt.review` },
  ];
  if (c.access !== "otc" || c.category === "Sunscreens")
    refs.unshift({ label: "DailyMed (NLM) — FDA-approved labeling", url: `https://dailymed.nlm.nih.gov/dailymed/search.cfm?labeltype=all&query=${q}` });
  return [...refs, ...(c.extraRefs ?? [])];
}

